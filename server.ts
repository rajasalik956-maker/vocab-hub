// Persistent server-side store for authoritative subscriptions, pending orders & payment receipts
const DATA_DIR = path.join(__dirname, 'data');
const STORE_PATH = path.join(DATA_DIR, 'subscriptions.json');

interface SubscriptionState {
  uid: string;
  email: string;
  tier: 'free' | 'premium';
  status: 'inactive' | 'active' | 'cancelled' | 'past_due';
  provider: 'none' | 'razorpay' | 'stripe';
  currentPeriodStart: string | null;
  currentPeriodEnd: string | null;
  cancelAtPeriodEnd: boolean;
  lastOrderId: string | null;
  lastPaymentId: string | null;
  updatedAt: string;
}

interface PendingOrder {
  id: string;
  uid: string;
  email: string;
  provider: 'razorpay' | 'stripe';
  amount: number;
  currency: string;
  status: 'created' | 'paid' | 'failed';
  mode: 'sandbox' | 'gateway';
  paymentId?: string;
  createdAt: string;
}

interface PaymentReceipt {
  id: string;
  uid: string;
  provider: 'razorpay' | 'stripe';
  orderId: string;
  paymentId: string;
  amount: number;
  currency: string;
  status: 'verified' | 'failed';
  mode: 'sandbox' | 'gateway';
  createdAt: string;
}

interface ServerStore {
  subscriptions: Record<string, SubscriptionState>;
  pendingOrders: Record<string, PendingOrder>;
  receipts: PaymentReceipt[];
}

function loadStore(): ServerStore {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    if (!fs.existsSync(STORE_PATH)) {
      const initial: ServerStore = { subscriptions: {}, pendingOrders: {}, receipts: [] };
      fs.writeFileSync(STORE_PATH, JSON.stringify(initial, null, 2));
      return initial;
    }
    return JSON.parse(fs.readFileSync(STORE_PATH, 'utf-8')) as ServerStore;
  } catch {
    return { subscriptions: {}, pendingOrders: {}, receipts: [] };
  }
}

function saveStore(store: ServerStore): void {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  fs.writeFileSync(STORE_PATH, JSON.stringify(store, null, 2));
}

